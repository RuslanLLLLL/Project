#pragma once

#include <QDateTime>
#include <QVector>

#include "ForecastTypes.h"

// =============================================================================
// Общая утилита определения доступности сети на интервале управления,
// используемая ОБОИМИ источниками прогноза (SQL - ForecastRepository, JSON -
// JsonForecastRepository). Вынесена отдельно, чтобы оба источника вели себя
// одинаково консервативно независимо от исходного разрешения данных
// (получасовые точки в SQL, минутные события включения/выключения в JSON).
//
// Раньше (до появления JSON-источника с минутным разрешением) ресэмплинг
// доступности сети был "ступенчатым": для интервала управления бралось
// значение gridOn ближайшей ПРЕДЫДУЩЕЙ точки данных, без учёта того, что
// внутри самого интервала отключение могло начаться/закончиться. Пока
// разрешение источника было не мельче периода управления (10 минут), это
// было не критично; при 5-минутных событиях из JSON интервал управления
// (15-60 минут) может содержать короткое отключение целиком внутри себя, и
// его нельзя было бы обнаружить. isIntervalFullyAvailable() устраняет это:
// интервал считается доступным только если сеть доступна НА ВСЁМ его
// протяжении - консервативно в сторону "не полагаться на сеть", а не наоборот.
// =============================================================================

// Точка перелома состояния сети: начиная с момента `at` сеть находится в
// состоянии `availableFrom` (и остаётся в нём до следующего перелома).
struct GridStateChange
{
    QDateTime at;
    bool availableFrom = true;
};

// Определяет, доступна ли сеть НА ПРОТЯЖЕНИИ ВСЕГО интервала
// [start, start + durationHours) по хронологически отсортированному (по
// возрастанию at) списку переломов состояния.
//
// defaultBeforeTimeline - состояние, которое считается действующим до самого
// первого элемента timeline (в т.ч. если timeline пуст целиком) - "нет данных
// вообще" трактуется как "сеть доступна" (соответствует поведению
// LoadScheduleController при отсутствии записей об отключениях).
//
// Логика: сначала находим состояние на момент start (последний перелом с
// at <= start, либо defaultBeforeTimeline, если такого нет). Если оно уже
// "недоступно" - интервал недоступен. Иначе проверяем, нет ли внутри
// интервала (start, start+durationHours) перелома В СТОРОНУ "недоступно" -
// если есть, интервал недоступен (консервативно), даже если отключение
// длилось лишь часть интервала.
bool isIntervalFullyAvailable(const QVector<GridStateChange> &timeline, const QDateTime &start,
                               double durationHours, bool defaultBeforeTimeline = true);

// Строит timeline из отсортированных по возрастанию timestamp точек SQL-
// источника (см. ForecastRepository::loadGridAvailability).
QVector<GridStateChange> buildTimelineFromPoints(const QVector<GridAvailabilityPoint> &points);
