#pragma once

// DispatchPermissions собирает четыре бинарные настройки, которые пользователь
// задаёт вручную в GUI (например, чекбоксами на панели диспетчера). Имена полей
// намеренно совпадают с именами, использованными в техническом задании, чтобы
// эту структуру можно было напрямую переиспользовать как набор членов класса
// существующего окна настроек.
//
// Все четыре флага влияют ТОЛЬКО на планирование (эвристика и MILP используют их
// как жёсткие ограничения) и на запись битов разрешений в регистр 2065/2100
// инвертора (см. InverterCommandMapper) — сам факт использования генератора/сети
// для покупки не запрещается: покупка из сети всегда разрешена (её ограничивает
// только gridMaxImportKw и наличие сети), эти же 4 флага касаются именно
// "необязательных" с точки зрения энергобаланса действий.
struct DispatchPermissions
{
    // Разрешение на запуск резервного генератора в принципе. Если false —
    // генератор не участвует в диспетчеризации, даже если он физически в составе
    // системы (registers Gen Signal/Gen Charge не выставляются).
    bool m_genEnable = false;

    // Разрешение заряжать СНЭ от резервного генератора (актуально, когда
    // генератор всё равно запущен для покрытия нагрузки и имеет свободную
    // мощность, или когда сеть недоступна длительное время).
    // Учитывается только если m_genEnable == true.
    bool m_genChargeEnable = false;

    // Разрешение продавать в сеть излишки мощности (солнце и/или СНЭ).
    // Если false — весь экспорт запрещён (излишки солнца, которые некуда
    // деть, будут ограничены/скошены — см. поле DispatchInterval::solarCurtailedKw).
    bool m_sollSell = true;

    // Разрешение разряжать СНЭ специально для продажи в сеть (в дополнение к
    // покрытию собственной нагрузки). Учитывается только если m_sollSell == true;
    // если m_sollSell == false, этот флаг не имеет эффекта (продажа запрещена
    // в принципе).
    bool m_sollSellOfBatteries = false;
};
