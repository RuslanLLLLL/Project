#pragma once

// SystemConfig описывает физические и тарифные параметры гибридной энергосистемы
// предприятия (сеть ограниченной мощности + СЭС + СНЭ + резервный генератор),
// построенной на инверторе Deye SUN...K-PCS01HP3. Значения по умолчанию — примерные,
// их нужно заменить проектными данными конкретного объекта.
//
// Структура сознательно не содержит Qt-типов, чтобы её можно было использовать
// и в модульных тестах, и в ядре оптимизатора без зависимости от GUI.
struct SystemConfig
{
    double gridMaxImportKw   = 200.0; // лимит мощности ввода из сети
    double gridMaxExportKw   = 200.0; // лимит мощности отдачи излишков в сеть
    double batteryCapacityKwh    = 500.0; // ёмкость СНЭ
    double batteryMaxChargeKw    = 200.0;  // макс. мощность заряда
    double batteryMaxDischargeKw = 200.0;  // макс. мощность разряда
    double chargeEfficiency      = 0.95;  // КПД заряда
    double dischargeEfficiency   = 0.95;  // КПД разряда
    double socMin     = 0.15; // мин. допустимый заряд, доля от ёмкости
    double socMax     = 0.90; // макс. допустимый заряд, доля от ёмкости
    double socReserve = 0.05; // дополнительный эксплуатационный резерв поверх socMin
    double genMaxPowerKw = 400.0; // макс. мощность резервного генератора
    double genCostPerKwh = 18.0;  // стоимость 1 кВт*ч от генератора
    double cycleCostPerFullCycle = 300.0; // стоимость одного полного цикла заряд-разряд СНЭ

    // Стоимость транспортировки электроэнергии, руб/кВт*ч - константа тарифа
    // (не зависит от часа/поставщика), добавляется к цене покупки buyPrice при
    // ЛЮБОМ расчёте стоимости импорта из сети (см. effectiveBuyPrice() ниже).
    // К цене продажи (sellPrice) не применяется - тариф на передачу платит
    // потребитель энергии, а не тот, кто отдаёт излишки в сеть.
    double gridTransportCostPerKwh = 0.0;
    // Пороги для классификации часов при эвристической диспетчеризации
    double cheapPricePercentile      = 0.30; // нижние 30% цен горизонта -> "дешёвые" часы
    double expensivePricePercentile  = 0.70; // верхние 30% цен горизонта -> "дорогие" часы

    // Штраф за недоотпуск нагрузки (руб/кВт*ч), используется только MILP-солвером,
    // чтобы модель всегда оставалась разрешимой (см. README, раздел про MILP).
    // Должен быть заведомо больше любой реальной цены покупки, чтобы солвер
    // задействовал этот "предохранитель" лишь в физически безвыходной ситуации
    // (сеть отключена, генератор запрещён/исчерпан, СНЭ разряжена до socMin).
    double lossOfLoadPenaltyPerKwh = 1000.0;
};

// Возвращает эффективную деградационную стоимость одного кВт*ч энергии, прошедшей
// через СНЭ (заряд ИЛИ разряд). Один "полный цикл" по определению — это заряд на
// всю ёмкость плюс последующий разряд на всю ёмкость, т.е. 2*batteryCapacityKwh
// кВт*ч суммарного энергопотока через батарею. Поэтому цена одного кВт*ч потока:
//     degradationCostPerKwh = cycleCostPerFullCycle / (2 * batteryCapacityKwh)
// Формула вынесена в inline-функцию, чтобы избежать рассогласования между
// эвристикой и MILP-моделью (см. README, "Стоимость цикла СНЭ").
inline double degradationCostPerKwh(const SystemConfig &cfg)
{
    if (cfg.batteryCapacityKwh <= 0.0)
        return 0.0;
    return cfg.cycleCostPerFullCycle / (2.0 * cfg.batteryCapacityKwh);
}

// Полная (эффективная) стоимость одного кВт*ч, купленного из сети - цена
// поставщика (buyPrice, приходит из прогноза - SQL или JSON) плюс константа
// стоимости транспортировки. ВСЕ финансовые расчёты (и в эвристике, и в MILP),
// связанные с покупкой из сети - выгода от разряда СНЭ вместо покупки, ценовой
// арбитраж, итоговая стоимость интервала - должны использовать именно эту
// функцию, а не "сырой" buyPrice напрямую, иначе стоимость транспортировки
// потерялась бы в части расчётов. Вынесена в inline-функцию по той же причине,
// что и degradationCostPerKwh() - чтобы не рассинхронизировать формулу между
// эвристикой и MILP-моделью.
inline double effectiveBuyPrice(const SystemConfig &cfg, double buyPrice)
{
    return buyPrice + cfg.gridTransportCostPerKwh;
}
