#pragma once

#include <QDateTime>
#include <QVector>

// -----------------------------------------------------------------------------
// Типы "сырых" данных, приходящих из SQL (см. README, раздел "Источник данных").
// -----------------------------------------------------------------------------

// Один час прогноза цен/генерации/нагрузки. Соответствует одной строке таблицы
// почасового прогноза, обновляемой раз в сутки в 13:00 на следующие сутки.
struct HourlyForecastPoint
{
    QDateTime timestamp; // начало часа, ISO 8601, локальная временная зона объекта
    double buyPrice  = 0.0; // цена покупки из сети, руб/кВт*ч
    double sellPrice = 0.0; // цена продажи излишков солнца в сеть, руб/кВт*ч
    double solarKw   = 0.0; // прогноз мощности СЭС на этот час, кВт
    double loadKw    = 0.0; // прогноз нагрузки предприятия на этот час, кВт
};

// Прогноз наличия сетевого подключения на получасовом интервале (возможны
// плановые отключения сети по графику).
struct GridAvailabilityPoint
{
    QDateTime timestamp; // начало получаса
    bool gridOn = true;  // true - сеть доступна, false - плановое отключение
};

// -----------------------------------------------------------------------------
// Внутреннее представление горизонта диспетчеризации после ресэмплинга.
// -----------------------------------------------------------------------------

// Один интервал управления (длительность = период оптимизации, настраиваемый
// пользователем в диапазоне 10..60 минут). Почасовые/получасовые входные данные
// "растягиваются" на интервалы управления ступенчато (см. ForecastRepository) —
// внутри одного часа все под-интервалы получают одно и то же значение цены,
// солнца и нагрузки, а внутри получаса - одно и то же значение gridOn.
struct DispatchIntervalForecast
{
    QDateTime timestamp;     // начало интервала управления
    double durationHours = 1.0; // длительность интервала, часы (controlPeriodMinutes/60)

    double buyPrice  = 0.0;  // руб/кВт*ч
    double sellPrice = 0.0;  // руб/кВт*ч
    double solarKw   = 0.0;  // кВт
    double loadKw    = 0.0;  // кВт
    bool   gridAvailable = true;
};

using ForecastHorizon = QVector<DispatchIntervalForecast>;

// Источник прогноза (цена/солнце/нагрузка/отключения сети), выбираемый
// пользователем. Оба источника производят один и тот же ForecastHorizon -
// DispatchEngine не знает, какой из них активен, кроме как для выбора, какой
// репозиторий вызвать (см. README, "Источник прогноза").
enum class ForecastSourceType
{
    // Вариант 1: SQL (ForecastRepository) - почасовые таблицы БД, см. README
    // "Источник данных (SQL)".
    Sql,

    // Вариант 2 (по умолчанию): JSON-файл loadSchedule.json (JsonForecastRepository) -
    // тот же файл, что ведёт LoadScheduleController в существующем интерфейсе
    // (почасовая нагрузка по участкам в %, единая цена, отключения сети по
    // минутным событиям, прогноз СЭС) - см. README, "Источник прогноза: JSON".
    Json
};
